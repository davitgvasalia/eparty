import "server-only";
import { randomBytes } from "crypto";
import { mkdir, readFile, unlink, writeFile } from "fs/promises";
import path from "path";
import { HttpError } from "./viewer";

// ID photos live outside public/ and are only served through an admin-only route.
// ID_PHOTO_DIR may be absolute (production) or relative to the project.
const DIR = path.resolve(process.cwd(), process.env.ID_PHOTO_DIR || "storage/ids");
const MAX_BYTES = 3 * 1024 * 1024;
const DATA_URL = /^data:image\/(jpeg|png|webp);base64,([A-Za-z0-9+/=]+)$/;

/** Validates an image data URL. Returns its bytes and file extension. */
export function decodeImage(dataUrl: unknown, field: string): { bytes: Buffer; ext: string } {
  const m = typeof dataUrl === "string" ? DATA_URL.exec(dataUrl) : null;
  if (!m) throw new HttpError(400, `${field} must be an image`);
  const bytes = Buffer.from(m[2], "base64");
  if (bytes.length > MAX_BYTES) throw new HttpError(400, `${field} is too large`);
  return { bytes, ext: m[1] === "jpeg" ? "jpg" : m[1] };
}

/** Saves the image under a random name and returns that name. */
export async function savePhoto(image: { bytes: Buffer; ext: string }): Promise<string> {
  await mkdir(DIR, { recursive: true });
  const name = `${randomBytes(16).toString("hex")}.${image.ext}`;
  await writeFile(path.join(DIR, name), image.bytes);
  return name;
}

export async function readPhoto(name: string): Promise<{ bytes: Buffer; type: string }> {
  // Names are generated by savePhoto; refuse anything that could leave the folder.
  if (!/^[0-9a-f]{32}\.(jpg|png|webp)$/.test(name)) throw new HttpError(404, "Not found");
  const ext = name.split(".").pop()!;
  const bytes = await readFile(path.join(DIR, name)).catch(() => {
    throw new HttpError(404, "Not found");
  });
  return { bytes, type: ext === "jpg" ? "image/jpeg" : `image/${ext}` };
}

export async function deletePhotos(...names: string[]) {
  await Promise.all(names.map((n) => unlink(path.join(DIR, n)).catch(() => {})));
}
