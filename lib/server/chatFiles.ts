import "server-only";
import { randomBytes } from "crypto";
import { mkdir, readFile, unlink, writeFile } from "fs/promises";
import path from "path";
import { HttpError } from "./viewer";

// Chat files live outside public/ and are served only to people in the chat. By default
// they sit next to the ID photo folder (storage/chat), which the server already lets the
// app write and backs up.
const DIR = path.resolve(
  process.cwd(),
  process.env.CHAT_FILE_DIR || path.join(path.dirname(process.env.ID_PHOTO_DIR || "storage/ids"), "chat")
);

/** Saves the bytes under a random name and returns that name. */
export async function saveChatFile(bytes: Buffer): Promise<string> {
  await mkdir(DIR, { recursive: true });
  const name = randomBytes(16).toString("hex");
  await writeFile(path.join(DIR, name), bytes);
  return name;
}

export async function readChatFile(name: string): Promise<Buffer> {
  // Names are generated by saveChatFile; refuse anything that could leave the folder.
  if (!/^[0-9a-f]{32}$/.test(name)) throw new HttpError(404, "Not found");
  return readFile(path.join(DIR, name)).catch(() => {
    throw new HttpError(404, "Not found");
  });
}

export async function deleteChatFiles(names: string[]) {
  await Promise.all(names.map((n) => unlink(path.join(DIR, n)).catch(() => {})));
}
